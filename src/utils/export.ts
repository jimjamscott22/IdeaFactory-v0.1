import { IdeaItem } from '../types/idea';
import { TimelineSchedule, formatPhaseWindow } from '../lib/timeline';

export function slugifyFilename(title: string): string {
  return (
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '') || 'project-spec'
  );
}

export function formatTimelineAsMarkdown(idea: IdeaItem, schedule: TimelineSchedule): string {
  const totalUnitLabel = `${schedule.totalDuration} ${schedule.unit}${schedule.totalDuration === 1 ? '' : 's'}`;
  const phaseSections = schedule.phases
    .map((phase) => {
      const windowLabel = formatPhaseWindow(phase, schedule.unit);
      const statusLabel =
        phase.status === 'completed'
          ? 'Completed'
          : phase.status === 'in_progress'
            ? 'In Progress'
            : 'Pending';

      const goalsBlock =
        phase.goals.length > 0
          ? `**Goals:**\n${phase.goals.map((g) => `- ${g}`).join('\n')}`
          : '';

      const deliverablesBlock =
        phase.milestones.length > 0
          ? `**Milestones & Deliverables (${phase.completedCount}/${phase.totalCount}):**\n${phase.milestones
              .map((m) => `- [${m.completed ? 'x' : ' '}] ${m.label}`)
              .join('\n')}`
          : '';

      return `## ${phase.phase}: ${phase.name}
- **Schedule Window:** ${windowLabel} (${phase.rawDuration})
- **Status:** ${statusLabel} (${phase.progressPercent}%)

${[goalsBlock, deliverablesBlock].filter(Boolean).join('\n\n')}`;
    })
    .join('\n\n---\n\n');

  return `# ${idea.title} — Project Timeline & Milestones
*${idea.tagline}*

- **Domain:** ${idea.domain}
- **Primary Language:** ${idea.language}
- **Complexity:** ${idea.complexity}
- **Estimated Build Time:** ${idea.estimatedHours}
- **Total Roadmap Span:** ${totalUnitLabel}
- **Overall Milestone Progress:** ${schedule.completedMilestones}/${schedule.totalMilestones} completed (${schedule.progressPercent}%)

---

${phaseSections}

---
*Exported from IdeaFactory Architecture Timeline*
`;
}

export function formatIdeaAsMarkdown(idea: IdeaItem): string {
  return `# ${idea.title}
*${idea.tagline}*

- **Primary Language:** ${idea.language}
- **Domain:** ${idea.domain}
- **Complexity:** ${idea.complexity}
- **Estimated Build Time:** ${idea.estimatedHours}
- **Tags:** ${idea.tags.join(', ')}

---

## 1. Problem Statement
${idea.problemStatement}

## 2. Core Architecture
${idea.coreArchitecture}

### Tech Stack
- **Primary Language:** ${idea.techStack.language}
${idea.techStack.framework ? `- **Framework:** ${idea.techStack.framework}\n` : ''}${idea.techStack.database ? `- **Database/Storage:** ${idea.techStack.database}\n` : ''}- **Protocols:** ${idea.techStack.protocols.join(', ')}
- **Key Libraries:** ${idea.techStack.libraries.join(', ')}

### Architecture Flow
${idea.architectureFlow.map((step, idx) => `${idx + 1}. ${step}`).join('\n')}

---

## 3. Key Technical Challenges & Edge Cases
${idea.keyChallenges
  .map(
    (c, idx) =>
      `### ${idx + 1}. ${c.title}
**Challenge:** ${c.description}  
**Mitigation Strategy:** ${c.solutionHint}
`
  )
  .join('\n')}

---

## 4. MVP Implementation Phases
${idea.mvpPhases
  .map(
    (p) => `### ${p.phase}: ${p.name} (${p.duration})
**Goals:**
${p.goals.map((g) => `- ${g}`).join('\n')}

**Deliverables:**
${p.deliverables.map((d) => `- ${d}`).join('\n')}
`
  )
  .join('\n')}

---

## 5. Learning Outcomes
${idea.learningOutcomes.map((l) => `- ${l}`).join('\n')}

## 6. Technical Interview Talking Points
${idea.interviewTalkingPoints.map((pt) => `- ${pt}`).join('\n')}

---
*Generated by IdeaFactory — Powered by Gemini 3.8 Flash*
`;
}

export function formatIdeaAsGitHubIssue(idea: IdeaItem): string {
  return `---
name: Feature / Project Spec: ${idea.title}
about: Full technical specification breakdown
title: "[SPEC] ${idea.title}"
labels: "${idea.language.toLowerCase()}, ${idea.domain.toLowerCase().replace(/[^a-z0-9]/g, '-')}, ${idea.complexity.toLowerCase().replace(/[^a-z0-9]/g, '-')}"
---

### Elevator Pitch
> ${idea.tagline}

### Context & Problem
${idea.problemStatement}

### Architectural Plan
${idea.coreArchitecture}

### Subsystems & Data Flow
${idea.architectureFlow.map((s) => `- [ ] ${s}`).join('\n')}

### MVP Checklist
${idea.mvpPhases
  .flatMap((phase) => [
    `#### ${phase.phase} - ${phase.name}`,
    ...phase.deliverables.map((d) => `- [ ] ${d}`),
  ])
  .join('\n')}

### Key Risks & Mitigations
${idea.keyChallenges.map((c) => `- **${c.title}**: ${c.solutionHint}`).join('\n')}
`;
}

export function downloadFile(filename: string, content: string, contentType = 'text/markdown') {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
