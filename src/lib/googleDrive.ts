export interface DriveUploadOptions {
  token: string;
  filename: string;
  content: string;
  mimeType?: string;
  description?: string;
  folderName?: string;
}

export interface DriveUploadResult {
  id: string;
  name: string;
  webViewLink?: string;
  isUpdate?: boolean;
}

const DRIVE_API_URL = 'https://www.googleapis.com/drive/v3';
const DRIVE_UPLOAD_URL = 'https://www.googleapis.com/upload/drive/v3';

/**
 * Searches for an existing folder by name or creates a new one in the user's root Drive.
 */
export async function getOrCreateFolder(
  token: string,
  folderName = 'IdeaFactory Specs'
): Promise<string> {
  const query = `name = '${folderName.replace(/'/g, "\\'")}' and mimeType = 'application/vnd.google-apps.folder' and trashed = false`;
  const searchUrl = `${DRIVE_API_URL}/files?q=${encodeURIComponent(query)}&fields=files(id,name)&spaces=drive`;

  const searchRes = await fetch(searchUrl, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/json',
    },
  });

  if (!searchRes.ok) {
    const errorData = await searchRes.json().catch(() => ({}));
    throw new Error(
      errorData.error?.message || `Failed to search Google Drive folders (${searchRes.status})`
    );
  }

  const searchData = await searchRes.json();
  if (Array.isArray(searchData.files) && searchData.files.length > 0) {
    return searchData.files[0].id;
  }

  // Create folder if not found
  const createRes = await fetch(`${DRIVE_API_URL}/files`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      name: folderName,
      mimeType: 'application/vnd.google-apps.folder',
      description: 'Exported technical specifications and roadmaps from IdeaFactory',
    }),
  });

  if (!createRes.ok) {
    const errorData = await createRes.json().catch(() => ({}));
    throw new Error(
      errorData.error?.message || `Failed to create folder in Google Drive (${createRes.status})`
    );
  }

  const createData = await createRes.json();
  return createData.id;
}

/**
 * Uploads or updates a file inside the IdeaFactory folder in Google Drive using multipart upload.
 */
export async function uploadSpecToDrive(
  options: DriveUploadOptions
): Promise<DriveUploadResult> {
  const {
    token,
    filename,
    content,
    mimeType = 'text/markdown',
    description = 'Technical specification generated by IdeaFactory',
    folderName = 'IdeaFactory Specs',
  } = options;

  const folderId = await getOrCreateFolder(token, folderName);

  // Check if file already exists in folder to update rather than creating duplicates
  const existingQuery = `name = '${filename.replace(/'/g, "\\'")}' and '${folderId}' in parents and trashed = false`;
  const existingRes = await fetch(
    `${DRIVE_API_URL}/files?q=${encodeURIComponent(existingQuery)}&fields=files(id,name,webViewLink)&spaces=drive`,
    {
      headers: { Authorization: `Bearer ${token}` },
    }
  );

  let existingFileId: string | null = null;
  if (existingRes.ok) {
    const existingData = await existingRes.json();
    if (existingData.files && existingData.files.length > 0) {
      existingFileId = existingData.files[0].id;
    }
  }

  const boundary = `-------IdeaFactoryBoundary${Date.now()}`;
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const metadata = existingFileId
    ? {
        name: filename,
        description,
        mimeType,
      }
    : {
        name: filename,
        parents: [folderId],
        description,
        mimeType,
      };

  const multipartRequestBody =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    `Content-Type: ${mimeType}; charset=UTF-8\r\n\r\n` +
    content +
    closeDelimiter;

  const endpoint = existingFileId
    ? `${DRIVE_UPLOAD_URL}/files/${existingFileId}?uploadType=multipart&fields=id,name,webViewLink`
    : `${DRIVE_UPLOAD_URL}/files?uploadType=multipart&fields=id,name,webViewLink`;

  const method = existingFileId ? 'PATCH' : 'POST';

  const res = await fetch(endpoint, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': `multipart/related; boundary=${boundary}`,
    },
    body: multipartRequestBody,
  });

  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}));
    throw new Error(
      errorData.error?.message || `Failed to save file to Google Drive (${res.status})`
    );
  }

  const data = await res.json();
  return {
    id: data.id,
    name: data.name || filename,
    webViewLink: data.webViewLink || `https://drive.google.com/file/d/${data.id}/view`,
    isUpdate: !!existingFileId,
  };
}
